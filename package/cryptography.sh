# Rust names the platform with its own vendor.
rust_target=$target_arch-unknown-$target_kernel-$target_abi

# The crates are downloaded with the source, each checked against its hash in Cargo.lock, which the
# source pins, and the build runs offline.
export CARGO_HOME=$DOWNLOAD_DIR/cargo

fetch() {
    default_fetch
    cargo fetch --locked --manifest-path $package_source_dir/Cargo.toml
}

# Only the extension module, which cargo builds by itself: the library that maturin would put in the
# wheel, next to the Python sources.
build() {
    # pyo3 reads the platform's Python in the sysroot, and links no libpython, as extension modules
    # do not. The C code of the OpenSSL bindings is generated by cffi, in the Python of TOOL_DIR, and
    # compiled with the platform's Python headers, which the build finds next to that library
    # directory.
    export PYO3_PYTHON=$TOOL_DIR/usr/bin/python3
    export PYO3_CROSS_LIB_DIR=$sysroot$prefix/lib/python${python_version%.*}
    export PYO3_BUILD_EXTENSION_MODULE=1
    export OPENSSL_DIR=$sysroot$prefix
    # The system's OpenSSL has no legacy provider, which cryptography would otherwise try to load.
    export CRYPTOGRAPHY_BUILD_OPENSSL_NO_LEGACY=1

    # The platform's code is compiled and linked by the cross toolchain, whose sysroot holds the
    # libraries. The paths of the crates' sources, which panic messages quote, are not those of
    # the build machine.
    export TARGET_CC=$host-gcc TARGET_AR=$host-ar
    export CARGO_TARGET_$(echo $rust_target | tr a-z- A-Z_)_LINKER=$host-gcc
    export RUSTFLAGS=--remap-path-prefix=$CARGO_HOME=/cargo
    export CARGO_PROFILE_RELEASE_STRIP=symbols

    cargo build --release --locked --offline --target $rust_target --target-dir target \
        --manifest-path $package_source_dir/src/rust/Cargo.toml
}

install() {
    local site_packages=$package_install_dir$prefix/lib/python${python_version%.*}/site-packages

    mkdir -pv $site_packages
    cp -rv $package_source_dir/src/cryptography $site_packages/
    cp -v target/$rust_target/release/libcryptography_rust.so \
        $site_packages/cryptography/hazmat/bindings/_rust.abi3.so
    python_compile
}
