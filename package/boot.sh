: ${package_version:=0.0.1}

install() {
    case $package_component in
        cmdline)
            mkdir -pv $package_install_dir/boot
            printf '%s\n' \
                "earlycon=pl011,0x20201000 console=ttyAMA0,115200" \
                "root=/dev/mmcblk0p2 rootfstype=btrfs rootflags=subvol=root/$ROOT_VOLUME" \
                "rw rootwait rootdelay=5" \
                "initcall_blacklist=bcm2835_pm_driver_init" \
                > $package_install_dir/boot/cmdline.txt
            # Collapse to a single space-separated line as the kernel expects
            tr '\n' ' ' < $package_install_dir/boot/cmdline.txt \
                > $package_install_dir/boot/cmdline.txt.tmp
            mv $package_install_dir/boot/cmdline.txt.tmp \
                $package_install_dir/boot/cmdline.txt
            ;;
        config)
            # RPi firmware config.txt — only used for real hardware boot
            # QEMU loads kernel/DTB directly without this file
            mkdir -pv $package_install_dir/boot
            cat > $package_install_dir/boot/config.txt <<EOF
# Raspberry Pi boot configuration
# Generated by lfs boot#config
arm_64bit=0
kernel=kernel.img
device_tree=${DTB##*/}
enable_uart=1
dtoverlay=disable-bt
EOF
            ;;
        *)
            default_install
            ;;
    esac
}
