: ${package_version:=0.1.0}

install() {
    case $package_component in
        cmdline)
            mkdir -pv $package_install_dir/boot
            # Cap-conditional read-only root (CAPS=amnesia, ambient here —
            # see lfs's qemu case for the QEMU-side twin of this same
            # substitution, and package/amnesia-config.sh for the rest of
            # the capability). rescue=nologreplay, NOT bare "nologreplay":
            # see lfs's qemu case for why even a `ro` mount needs it, and
            # why the bare spelling panics this kernel. Defaults (rootflags/
            # rwmode) match the pre-amnesia text exactly, so a no-amnesia
            # build's cmdline.txt is byte-identical to before this
            # capability existed.
            local rootflags=subvol=root/$ROOT_VOLUME
            local rwmode=rw
            case " ${CAPS:-} " in
                *" amnesia "*)
                    rootflags=$rootflags,rescue=nologreplay
                    rwmode=ro
                    ;;
            esac
            printf '%s\n' \
                "earlycon=pl011,0x20201000 console=ttyAMA0,115200" \
                "root=/dev/mmcblk0p2 rootfstype=btrfs rootflags=$rootflags" \
                "$rwmode rootwait rootdelay=5" \
                "initcall_blacklist=bcm2835_pm_driver_init" \
                > $package_install_dir/boot/cmdline.txt
            # Collapse to a single space-separated line as the kernel expects
            tr '\n' ' ' < $package_install_dir/boot/cmdline.txt \
                > $package_install_dir/boot/cmdline.txt.tmp
            mv $package_install_dir/boot/cmdline.txt.tmp \
                $package_install_dir/boot/cmdline.txt
            ;;
        config)
            # RPi firmware config.txt — only used for real hardware boot
            # QEMU loads kernel/DTB directly without this file
            mkdir -pv $package_install_dir/boot
            cat > $package_install_dir/boot/config.txt <<EOF
# Raspberry Pi boot configuration
# Generated by lfs boot#config
arm_64bit=0
kernel=kernel.img
device_tree=${DTB##*/}
enable_uart=1
dtoverlay=disable-bt
EOF
            ;;
        *)
            default_install
            ;;
    esac
}
